const fs = require('fs');
const PDFDocument = require('pdfkit');

/**
 * Format bytes to readable string (KB, MB, GB)
 */
function formatBytes(bytes) {
  const n = Number(bytes) || 0;
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  if (n < 1024 * 1024 * 1024) return `${(n / (1024 * 1024)).toFixed(1)} MB`;
  return `${(n / (1024 * 1024 * 1024)).toFixed(2)} GB`;
}

/**
 * Formats a Date object or string to readable local date-time
 */
function formatDateTime(d) {
  if (!d) return 'N/A';
  const dt = d instanceof Date ? d : new Date(d);
  if (isNaN(dt.getTime())) return String(d);
  return dt.toLocaleString();
}

/**
 * Draws a table on the PDF document with pagination and alternate row shading
 */
function drawTable(doc, { headers, colWidths, rows, startX = 40 }) {
  const tableWidth = colWidths.reduce((a, b) => a + b, 0);
  const rowHeight = 20;

  function printHeader() {
    doc.rect(startX, doc.y, tableWidth, rowHeight).fill('#e2e8f0');
    doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(8);

    let curX = startX;
    headers.forEach((h, i) => {
      doc.text(h, curX + 4, doc.y + 5, {
        width: colWidths[i] - 8,
        align: i >= colWidths.length - 2 ? 'right' : 'left',
      });
      curX += colWidths[i];
    });
    doc.y += rowHeight;
  }

  printHeader();

  rows.forEach((row, rowIndex) => {
    // Check if new page is needed
    if (doc.y + rowHeight > doc.page.height - 50) {
      doc.addPage();
      printHeader();
    }

    // Alternate shading
    if (rowIndex % 2 === 1) {
      doc.rect(startX, doc.y, tableWidth, rowHeight).fill('#f8fafc');
    }

    doc.fillColor('#334155').font('Helvetica').fontSize(8);

    let curX = startX;
    row.forEach((cell, i) => {
      const textVal = String(cell !== null && cell !== undefined ? cell : '');
      doc.text(textVal, curX + 4, doc.y + 5, {
        width: colWidths[i] - 8,
        align: i >= colWidths.length - 2 ? 'right' : 'left',
      });
      curX += colWidths[i];
    });

    doc.y += rowHeight;
  });

  doc.y += 10;
}

/**
 * Generates a styled PDF report and writes it to filePath
 * @param {object} reportData
 * @param {string} filePath
 * @param {string} userName
 * @returns {Promise<string>}
 */
function generatePdf(reportData, filePath, userName = 'System') {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4',
      margin: 40,
      bufferPages: true,
      autoFirstPage: true,
    });

    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    const typeTitle = reportData.report_type.charAt(0).toUpperCase() + reportData.report_type.slice(1);

    // --- Header Banner ---
    doc.rect(40, 40, 515, 60).fill('#0f172a');
    doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(18)
      .text(`NetSentinel — ${typeTitle} Report`, 55, 52);
    doc.font('Helvetica').fontSize(9).fillColor('#94a3b8')
      .text('Automated Network Traffic & Intrusion Detection System', 55, 75);

    doc.y = 115;

    // --- Metadata Block ---
    doc.fillColor('#1e293b').font('Helvetica-Bold').fontSize(9).text('Report Metadata');
    doc.rect(40, doc.y + 4, 515, 45).fill('#f1f5f9');

    const metaY = doc.y + 10;
    doc.fillColor('#475569').font('Helvetica').fontSize(8);
    doc.text(`Generated By: ${userName}`, 50, metaY);
    doc.text(`Generated At: ${formatDateTime(new Date())}`, 50, metaY + 14);

    doc.text(`Start Time: ${formatDateTime(reportData.start_time)}`, 280, metaY);
    doc.text(`End Time: ${formatDateTime(reportData.end_time)}`, 280, metaY + 14);

    doc.y = 180;

    // --- Report Type Specific Content ---
    if (reportData.report_type === 'traffic') {
      const summary = reportData.summary || {};

      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(11).text('Traffic Summary');
      doc.y += 4;

      // Summary KPI Grid
      const kpis = [
        ['Total Packets', summary.total_packets?.toLocaleString() || '0'],
        ['Total Volume', formatBytes(summary.total_bytes)],
        ['Unique Sources', String(summary.unique_sources || 0)],
        ['Unique Destinations', String(summary.unique_destinations || 0)],
      ];

      const kpiWidth = 120;
      kpis.forEach(([label, val], idx) => {
        const kX = 40 + idx * 130;
        doc.rect(kX, doc.y, kpiWidth, 36).fill('#f8fafc').stroke('#cbd5e1');
        doc.fillColor('#64748b').font('Helvetica').fontSize(7).text(label, kX + 6, doc.y + 6);
        doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(11).text(val, kX + 6, doc.y + 16);
      });

      doc.y += 48;

      // Protocol Distribution
      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(10).text('Protocol Distribution');
      doc.y += 4;
      const protoRows = (reportData.protocol_distribution || []).map((p) => [
        p.protocol,
        p.count.toLocaleString(),
        formatBytes(p.bytes),
      ]);
      drawTable(doc, {
        headers: ['Protocol', 'Packet Count', 'Total Volume'],
        colWidths: [200, 150, 165],
        rows: protoRows.length > 0 ? protoRows : [['No protocol traffic recorded', '0', '0 B']],
      });

      // Top Talkers
      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(10).text('Top 10 Source Talkers');
      doc.y += 4;
      const talkerRows = (reportData.top_talkers || []).map((t) => [
        t.ip,
        t.packets.toLocaleString(),
        formatBytes(t.bytes),
      ]);
      drawTable(doc, {
        headers: ['Source IP', 'Packets Sent', 'Total Bytes'],
        colWidths: [220, 140, 155],
        rows: talkerRows.length > 0 ? talkerRows : [['No data', '0', '0 B']],
      });

      // Top Ports
      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(10).text('Top 10 Destination Ports');
      doc.y += 4;
      const portRows = (reportData.top_ports || []).map((p) => [
        String(p.port),
        p.count.toLocaleString(),
        formatBytes(p.bytes),
      ]);
      drawTable(doc, {
        headers: ['Destination Port', 'Packets Received', 'Total Volume'],
        colWidths: [180, 160, 175],
        rows: portRows.length > 0 ? portRows : [['No data', '0', '0 B']],
      });
    } else if (reportData.report_type === 'alerts') {
      const summary = reportData.summary || {};

      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(11).text('Intrusion Detection Summary');
      doc.y += 4;

      const kpis = [
        ['Total Alerts', String(summary.total_alerts || 0)],
        ['Critical Alerts', String(summary.by_severity?.find((s) => s.severity === 'critical')?.count || 0)],
        ['High Alerts', String(summary.by_severity?.find((s) => s.severity === 'high')?.count || 0)],
        ['Open / New', String(summary.by_status?.find((s) => s.status === 'new')?.count || 0)],
      ];

      kpis.forEach(([label, val], idx) => {
        const kX = 40 + idx * 130;
        doc.rect(kX, doc.y, 120, 36).fill('#f8fafc').stroke('#cbd5e1');
        doc.fillColor('#64748b').font('Helvetica').fontSize(7).text(label, kX + 6, doc.y + 6);
        doc.fillColor(idx === 1 ? '#dc2626' : idx === 2 ? '#ea580c' : '#0f172a')
          .font('Helvetica-Bold').fontSize(11).text(val, kX + 6, doc.y + 16);
      });

      doc.y += 48;

      // Alerts List
      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(10).text('Detected Security Alerts');
      doc.y += 4;

      const alertRows = (reportData.alerts || []).map((a) => [
        String(a.id),
        formatDateTime(a.timestamp),
        a.rule_name || a.alert_type,
        a.severity.toUpperCase(),
        a.source_ip,
        a.status.toUpperCase(),
      ]);

      drawTable(doc, {
        headers: ['ID', 'Timestamp', 'Rule / Attack Type', 'Severity', 'Source IP', 'Status'],
        colWidths: [35, 115, 135, 65, 100, 65],
        rows: alertRows.length > 0 ? alertRows : [['-', 'No alerts in selected timeframe', '-', '-', '-', '-']],
      });
    } else if (reportData.report_type === 'devices') {
      const devices = reportData.devices || [];

      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(11).text('Network Devices & Risk Posture');
      doc.y += 4;

      const highRiskCount = devices.filter((d) => d.risk_level === 'high' || d.risk_level === 'critical').length;
      const kpis = [
        ['Total Devices', String(devices.length)],
        ['High/Crit Risk', String(highRiskCount)],
        ['Total Traffic', formatBytes(devices.reduce((acc, d) => acc + d.bytes, 0))],
        ['Total Alerts', String(devices.reduce((acc, d) => acc + d.alerts, 0))],
      ];

      kpis.forEach(([label, val], idx) => {
        const kX = 40 + idx * 130;
        doc.rect(kX, doc.y, 120, 36).fill('#f8fafc').stroke('#cbd5e1');
        doc.fillColor('#64748b').font('Helvetica').fontSize(7).text(label, kX + 6, doc.y + 6);
        doc.fillColor(idx === 1 && highRiskCount > 0 ? '#dc2626' : '#0f172a')
          .font('Helvetica-Bold').fontSize(11).text(val, kX + 6, doc.y + 16);
      });

      doc.y += 48;

      // Devices Table
      doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(10).text('Device Inventory & Risk Assessment');
      doc.y += 4;

      const deviceRows = devices.map((d) => [
        d.ip_address,
        d.hostname || d.device_type || 'unknown',
        d.packets.toLocaleString(),
        formatBytes(d.bytes),
        String(d.alerts),
        String(d.risk_score),
        d.risk_level.toUpperCase(),
      ]);

      drawTable(doc, {
        headers: ['IP Address', 'Hostname/Type', 'Packets', 'Bytes', 'Alerts', 'Score', 'Risk'],
        colWidths: [100, 115, 65, 75, 50, 50, 60],
        rows: deviceRows.length > 0 ? deviceRows : [['No devices active in timeframe', '-', '-', '-', '-', '-', '-']],
      });
    }

    // --- Two-pass Page Numbering in Footer ---
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.fillColor('#94a3b8').font('Helvetica').fontSize(8).text(
        `NetSentinel Security Report  |  Page ${i + 1} of ${range.count}`,
        40,
        doc.page.height - 30,
        { align: 'center', width: 515 }
      );
    }

    doc.end();

    stream.on('finish', () => resolve(filePath));
    stream.on('error', (err) => reject(err));
  });
}

module.exports = {
  generatePdf,
  formatBytes,
  formatDateTime,
};
